"""Generate value types from the checked-in OpenAPI, without external dependencies."""
import argparse, json, pathlib
root = pathlib.Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--schema', type=pathlib.Path, default=root.parent/'api/openapi.json')
args = parser.parse_args()
schemas = json.loads(args.schema.read_text())['components']['schemas']
def typ(p):
 if '$ref' in p:return p['$ref'].split('/')[-1]
 if 'anyOf' in p:
  nonnull=[x for x in p['anyOf'] if x.get('type')!='null']
  return typ(nonnull[0]) if len(nonnull)==1 else 'JSONValue'
 t=p.get('type')
 if t=='array':return '['+typ(p['items'])+']'
 if t=='object':return '[String: '+typ(p.get('additionalProperties',{}))+']'
 return {'string':'String','number':'Double','integer':'Int','boolean':'Bool'}.get(t,'JSONValue')
def val(v):
 if v is None:return 'nil'
 if isinstance(v,bool):return str(v).lower()
 if isinstance(v,str):return json.dumps(v,ensure_ascii=False)
 if isinstance(v,list):return '['+', '.join(val(x) for x in v)+']'
 return str(v)
out=['// Generated by script/generate_models.py from the supplied OpenAPI schema.','import Foundation','']
for name,s in schemas.items():
 out += ['struct '+name+': Codable, Sendable'+(', Identifiable' if 'id' in s.get('required',[]) else '')+(', Equatable' if name == 'WorkLineIn' else '')+' {']
 for key,p in s.get('properties',{}).items():
  optional=key not in s.get('required',[]) or any(x.get('type')=='null' for x in p.get('anyOf',[]))
  # Schema defaults remain nonoptional so SwiftUI controls can bind directly.
  if 'default' in p:optional=False
  t=typ(p)+('?' if optional else '')
  d=(' = '+val(p['default'])) if 'default' in p else (' = nil' if optional else '')
  out+=['    var '+('`'+key+'`' if key in ['default','repeat'] else key)+': '+t+d]
 out+=['}','']
(root/'Models/APIModels.swift').write_text('\n'.join(out))
